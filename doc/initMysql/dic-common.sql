-- 字典服务 数据库脚本

-- 创建数据库 dic-common
CREATE DATABASE IF NOT EXISTS `dic-common` DEFAULT CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;

-- 使用该数据库
USE `dic-common`;

DROP TABLE IF EXISTS `dic_nation`;
CREATE TABLE `dic_nation`  (
                               `nation_code` char(2) NOT NULL COMMENT '民族编码',
                               `nation_name` varchar(64) NULL DEFAULT NULL COMMENT '民族名称',
                               PRIMARY KEY (`nation_code`) USING BTREE
) ENGINE = InnoDB;

